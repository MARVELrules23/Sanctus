"""Novenas — nine-day devotional prayers.

Each novena ships with its AUTHENTIC traditional prayer (recited each day). A
short daily *contemplation* is generated by AI as the user progresses and is
cached permanently per (novena, day). Users pick their own start date; the
novena then runs nine consecutive days. Only one novena is active at a time,
but it can be restarted if abandoned.

All prayer + reflection text is localized into the user's language (EN/ES/IT)
through the shared, permanently-cached translator.
"""
