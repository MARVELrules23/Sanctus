NOVENA_BY_SLUG = {n["slug"]: n for n in NOVENAS}


def _public_catalog(n: Dict[str, Any]) -> Dict[str, Any]:
    return {
        "slug": n["slug"], "name": n["name"], "patron": n["patron"],
        "feast": n["feast"], "theme": n["theme"], "color": n["color"], "icon": n["icon"],
        "intro": n["intro"], "days": 9,
    }


def _public_detail(n: Dict[str, Any]) -> Dict[str, Any]:
    out = _public_catalog(n)
    out["main_prayer"] = n["main_prayer"]
    out["day_intentions"] = n.get("day_intentions")  # may be None
    return out


def _parse_date(v: str) -> date:
    return datetime.strptime(v, "%Y-%m-%d").date()


def _enrollment_public(e: Dict[str, Any]) -> Dict[str, Any]:
    start = e["start_date"]
    end = (_parse_date(start) + timedelta(days=8)).isoformat()
    completed = sorted(set(e.get("completed_days", [])))
    return {
        "slug": e["slug"], "start_date": start, "end_date": end,
        "completed_days": completed, "status": e.get("status", "active"),
        "total_days": 9,
    }


async def _localize_strings(db, values: List[str]) -> List[str]:
    lang = get_lang()
    if lang == "en" or not values:
        return values
    try:
        from i18n_translate import translate_texts
        return await translate_texts(db, os.environ.get("EMERGENT_LLM_KEY", ""), values, lang)
    except Exception:  # noqa: BLE001
        return values


async def _reflection(db, emergent_llm_key: str, n: Dict[str, Any], day: int) -> str:
    """Return (and cache) the AI daily contemplation for a novena day, in English."""
    col = db["novena_reflections"]
    doc = await col.find_one({"slug": n["slug"], "day": day}, {"_id": 0, "text": 1})
    if doc and (doc.get("text") or "").strip():
        return doc["text"].strip()
    intention = ""
    if n.get("day_intentions") and 1 <= day <= len(n["day_intentions"]):
        intention = f" Today's traditional intention: {n['day_intentions'][day - 1]}"
    system = (
        "You are a faithful Catholic spiritual director writing a brief daily contemplation for a novena. "
        "Write 2-3 warm, reverent sentences (max ~55 words) that the person can carry through the day. "
        "Stay orthodox and Scripture-rooted; no headings, no markdown, plain prose."
    )
    user = (
        f"Novena: {n['name']} (to {n['patron']}). Theme: {n['theme']}. "
        f"This is Day {day} of 9.{intention} "
        "Give a short contemplation tying today to the novena's theme and to growth in trust and love of God."
    )
    text = ""
    try:
        from emergentintegrations.llm.chat import LlmChat, UserMessage
        chat = LlmChat(api_key=emergent_llm_key, session_id=f"nov-{n['slug']}-{day}", system_message=system).with_model("anthropic", MODEL)
        resp = await chat.send_message(UserMessage(text=user))
        text = (resp if isinstance(resp, str) else str(resp)).strip()
    except Exception:  # noqa: BLE001
        text = ""
    if text:
        await col.update_one({"slug": n["slug"], "day": day}, {"$set": {"slug": n["slug"], "day": day, "text": text}}, upsert=True)
    return text


class StartModel(BaseModel):
    start_date: str  # YYYY-MM-DD


class DayModel(BaseModel):
    day: int


def build_router(db: AsyncIOMotorDatabase, get_current_user, emergent_llm_key: str = "") -> APIRouter:
    router = APIRouter(prefix="/novenas", tags=["novenas"])
    enroll = db["novena_enrollments"]

    async def _active(user_id: str) -> Optional[Dict[str, Any]]:
        return await enroll.find_one({"user_id": user_id, "status": "active"}, {"_id": 0})

    @router.get("")
    async def list_novenas(user=Depends(get_current_user)):
        items = [_public_catalog(n) for n in NOVENAS]
        names = await _localize_strings(db, [i["name"] for i in items])
        themes = await _localize_strings(db, [i["theme"] for i in items])
        for it, nm, th in zip(items, names, themes):
            it["name"], it["theme"] = nm, th
        active = await _active(user.user_id)
        return {"items": items, "active": _enrollment_public(active) if active else None}

    @router.get("/active")
    async def get_active(user=Depends(get_current_user)):
        a = await _active(user.user_id)
        if not a:
            return {"active": None}
        out = _enrollment_public(a)
        out["novena"] = _public_catalog(NOVENA_BY_SLUG[a["slug"]])
        return {"active": out}

    @router.post("/{slug}/start")
    async def start(slug: str, payload: StartModel, user=Depends(get_current_user)):
        n = NOVENA_BY_SLUG.get(slug)
        if not n:
            raise HTTPException(status_code=404, detail="Novena not found")
        try:
            _parse_date(payload.start_date)
        except ValueError:
            raise HTTPException(status_code=400, detail="start_date must be YYYY-MM-DD")
        existing = await _active(user.user_id)
        if existing and existing["slug"] != slug:
            raise HTTPException(
                status_code=409,
                detail={"message": "You already have an active novena.", "active_slug": existing["slug"]},
            )
        # (Re)start: replace any prior enrollment for this user+slug.
        await enroll.delete_many({"user_id": user.user_id, "slug": slug})
        doc = {
            "user_id": user.user_id, "slug": slug, "start_date": payload.start_date,
            "completed_days": [], "status": "active",
            "created_at": datetime.now(timezone.utc).isoformat(),
        }
        await enroll.insert_one(dict(doc))
        return _enrollment_public(doc)

    @router.post("/stop")
    async def stop(user=Depends(get_current_user)):
        await enroll.update_many({"user_id": user.user_id, "status": "active"}, {"$set": {"status": "abandoned"}})
        return {"ok": True}

    @router.post("/{slug}/complete-day")
    async def complete_day(slug: str, payload: DayModel, user=Depends(get_current_user)):
        if payload.day < 1 or payload.day > 9:
            raise HTTPException(status_code=400, detail="day must be 1-9")
        e = await enroll.find_one({"user_id": user.user_id, "slug": slug, "status": "active"})
        if not e:
            raise HTTPException(status_code=404, detail="No active enrollment for this novena")
        done = sorted(set(e.get("completed_days", [])) | {payload.day})
        status = "completed" if len(done) >= 9 else "active"
        await enroll.update_one({"_id": e["_id"]}, {"$set": {"completed_days": done, "status": status}})
        e["completed_days"], e["status"] = done, status
        return _enrollment_public(e)

    @router.get("/{slug}")
    async def get_one(slug: str, user=Depends(get_current_user)):
        n = NOVENA_BY_SLUG.get(slug)
        if not n:
            raise HTTPException(status_code=404, detail="Novena not found")
        out = _public_detail(n)
        # Localize name/theme/intro/main_prayer/day_intentions
        base = [out["name"], out["theme"], out["intro"], out["main_prayer"]]
        di = out.get("day_intentions") or []
        tr = await _localize_strings(db, base + list(di))
        out["name"], out["theme"], out["intro"], out["main_prayer"] = tr[0], tr[1], tr[2], tr[3]
        if di:
            out["day_intentions"] = tr[4:4 + len(di)]
        e = await enroll.find_one({"user_id": user.user_id, "slug": slug, "status": {"$in": ["active", "completed"]}}, {"_id": 0})
        out["enrollment"] = _enrollment_public(e) if e else None
        return out

    @router.get("/{slug}/reflection/{day}")
    async def reflection(slug: str, day: int, user=Depends(get_current_user)):
        n = NOVENA_BY_SLUG.get(slug)
        if not n:
            raise HTTPException(status_code=404, detail="Novena not found")
        if day < 1 or day > 9:
            raise HTTPException(status_code=400, detail="day must be 1-9")
        text_en = await _reflection(db, emergent_llm_key, n, day)
        [text] = await _localize_strings(db, [text_en]) if text_en else [""]
        return {"slug": slug, "day": day, "reflection": text}

    return router
